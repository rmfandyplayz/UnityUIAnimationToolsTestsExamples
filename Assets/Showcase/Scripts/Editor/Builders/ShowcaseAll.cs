using System.Collections.Generic;
using System.IO;
using System.Text;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;

namespace UIAnimLab.Showcase.Builders
{
    /// <summary>Builds every showcase scene, and writes SHOTLIST.md from what they hold.</summary>
    public static class ShowcaseAll
    {
        public const string ShotList = "Assets/Showcase/SHOTLIST.md";

        [MenuItem(SC.Menu + "Build All", priority = 0)]
        public static void BuildAll()
        {
            BasicsShowcase.YourFirstAnimation();
            BasicsShowcase.Steps();
            BasicsShowcase.FromAndTo();
            BasicsShowcase.Targets();
            BasicsShowcase.Easing();
            EditorShowcase.Previewing();
            EditorShowcase.Recording();
            ExamplesShowcase.Build();
            MotionShowcase.PunchAndShake();
            MotionShowcase.Sizing();
            MotionShowcase.MovementPaths();
            ValuesShowcase.Sound();
            ValuesShowcase.CustomProperty();
            ValuesShowcase.Materials();
            MotionShowcase.StylisedMotion();
            MotionShowcase.Interrupting();
            EditorShowcase.Mirroring();
            EditorShowcase.CopyPaste();
            EditorShowcase.AnimationSets();
            EditorShowcase.SceneGizmos();
            EditorShowcase.Warnings();
            WriteShotList();
        }

        /// <summary>One section per wiki page, one entry per frame: what it shows, what to capture, and how.</summary>
        [MenuItem(SC.Menu + "Write SHOTLIST.md", priority = 1)]
        public static void WriteShotList()
        {
            var md = new StringBuilder();
            md.AppendLine("# Showcase shot list");
            md.AppendLine();
            md.AppendLine("Generated by **Tools → UI Anim Lab → Build Showcase → Write SHOTLIST.md** from the frames in `Assets/Showcase/Scenes`. Don't edit by hand: change the builders in `Assets/Showcase/Scripts/Editor/Builders` and rebuild.");
            md.AppendLine();
            md.AppendLine("**Recording a GIF:** open the page's scene, set the Game view to a 16:9 resolution (1920 x 1080 or 1280 x 720), enter play mode. The board starts focused on frame 1; **Tab** moves to the next frame, number keys jump. With a frame focused: **Space** plays it, **R** puts it back, **L** loops it. Frames with buttons or hover can also be used directly with the mouse.");
            md.AppendLine();
            md.AppendLine("**Screenshots of the Editor:** select the frame (or the object named under Watch) out of play mode; the frame's own Inspector repeats these directions.");
            md.AppendLine();

            var guids = AssetDatabase.FindAssets("t:Scene", new[] { SC.Scenes.TrimEnd('/') });
            var paths = new List<string>();
            foreach (var g in guids) paths.Add(AssetDatabase.GUIDToAssetPath(g));
            paths.Sort();

            foreach (var path in paths)
            {
                var existing = UnityEngine.SceneManagement.SceneManager.GetSceneByPath(path);
                bool wasOpen = existing.IsValid() && existing.isLoaded;
                var scene = wasOpen ? existing : EditorSceneManager.OpenScene(path, OpenSceneMode.Additive);

                var stations = new List<Station>();
                foreach (var root in scene.GetRootGameObjects()) stations.AddRange(root.GetComponentsInChildren<Station>(true));

                string page = null;
                int frame = 0;
                foreach (var s in stations)
                {
                    if (s.Style == StationStyle.Readme)
                    {
                        page = s.Title;
                        md.AppendLine("## " + page);
                        md.AppendLine();
                        md.AppendLine("Scene: `" + path + "`");
                        md.AppendLine();
                        continue;
                    }

                    frame++;
                    md.AppendLine("### " + frame + ". " + s.Title);
                    md.AppendLine();
                    md.AppendLine("- **Shows:** " + Plain(s.Summary));
                    md.AppendLine("- **Capture:** " + Plain(s.Capture));
                    if (!string.IsNullOrEmpty(s.HowTo)) md.AppendLine("- **Set up:** " + Plain(s.HowTo));
                    if (!string.IsNullOrEmpty(s.Watch)) md.AppendLine("- **Select:** " + Plain(s.Watch));
                    md.AppendLine("- **Needs:** " + (s.Needs == StationNeeds.None ? "the Editor, out of play mode" : Station.BadgesOf(s.Needs).ToLowerInvariant()));
                    md.AppendLine();
                }

                if (!wasOpen) EditorSceneManager.CloseScene(scene, true);
            }

            File.WriteAllText(ShotList, md.ToString().Replace("\r\n", "\n"));
            AssetDatabase.ImportAsset(ShotList);
            Debug.Log("UI Anim Lab: wrote " + ShotList);
        }

        // Rich text to Markdown: bold stays bold, any other tag goes.
        private static string Plain(string text)
        {
            if (string.IsNullOrEmpty(text)) return "-";
            text = text.Replace("<b>", "**").Replace("</b>", "**");
            return System.Text.RegularExpressions.Regex.Replace(text, "<[^>]+>", "").Replace("\n", " ");
        }
    }
}
